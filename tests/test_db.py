"""Tests for the dual-engine DB helper (``scripts/db.py``).

These guard the contract that switching engines is configuration-only:
URL resolution, ``?``/DDL translation, the sqlite roundtrip, and dict-like
rows. The PostgreSQL case runs only when ``ZOLAI_TEST_PG_URL`` points at a
scratch database (see ``scripts/README-db.md``).
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "scripts"))

import db  # noqa: E402


def test_translate_ddl_drops_pragmas_behind_comments():
    script = (
        "-- schema header\n"
        "PRAGMA journal_mode=WAL;\n"
        "-- dictionary\n"
        "CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT);"
    )
    statements = db.translate_ddl(script)
    assert len(statements) == 1
    assert statements[0].startswith("CREATE TABLE t")
    assert "AUTOINCREMENT" not in statements[0]
    assert "GENERATED BY DEFAULT AS IDENTITY" in statements[0]


def test_translate_ddl_keeps_portable_statements():
    assert db.translate_ddl("CREATE TABLE x (id INTEGER)") == ["CREATE TABLE x (id INTEGER)"]
    assert db.translate_ddl("-- only a comment") == []


@pytest.mark.parametrize(
    ("url", "dialect"),
    [
        ("sqlite:///:memory:", "sqlite"),
        ("postgresql://u:p@localhost:5432/zolai", "postgres"),
        ("postgres://u:p@localhost:5432/zolai", "postgres"),
    ],
)
def test_resolve_url_dialects(monkeypatch, url, dialect):
    monkeypatch.delenv("ZOLAI_DB_URL", raising=False)
    assert db.resolve_url(url)[0] == dialect


def test_env_overrides_explicit_argument(monkeypatch):
    monkeypatch.setenv("ZOLAI_DB_URL", "postgresql://u:p@localhost:5432/zolai")
    assert db.resolve_url("data/zolai.db")[0] == "postgres"


def test_row_is_dict_like():
    row = db.Row(("a", "b"), (1, 2))
    assert row[0] == 1 and row["b"] == 2
    assert row.keys() == ("a", "b")
    assert list(row) == [1, 2]
    assert dict(row) == {"a": 1, "b": 2}
    assert db.row_to_dict(row) == {"a": 1, "b": 2}
    assert db.row_to_dict(None) is None


def test_sqlite_roundtrip(monkeypatch):
    monkeypatch.delenv("ZOLAI_DB_URL", raising=False)
    conn = db.connect("sqlite:///:memory:")
    try:
        assert conn.dialect == "sqlite"
        conn.executescript(
            "-- header\nPRAGMA journal_mode=WAL;\n"
            "CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT);"
        )
        conn.execute("INSERT INTO t (name) VALUES (?)", ("zolai",))
        conn.commit()
        row = conn.fetchone("SELECT id, name FROM t")
        assert db.row_to_dict(row) == {"id": 1, "name": "zolai"}
        assert row[0] == 1 and row["name"] == "zolai"
    finally:
        conn.close()


@pytest.mark.skipif(
    not os.environ.get("ZOLAI_TEST_PG_URL"),
    reason="ZOLAI_TEST_PG_URL not set (needs a scratch PostgreSQL database)",
)
def test_postgres_roundtrip(monkeypatch):
    monkeypatch.setenv("ZOLAI_DB_URL", os.environ["ZOLAI_TEST_PG_URL"])
    conn = db.connect()
    assert conn.dialect == "postgres"
    try:
        conn.executescript(
            "DROP TABLE IF EXISTS db_helper_test;"
            "CREATE TABLE db_helper_test ("
            " id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL UNIQUE);"
        )
        conn.execute("INSERT INTO db_helper_test (name) VALUES (?)", ("zolai",))
        conn.commit()
        # upsert on the unique column, the portable form used by the scripts
        conn.execute(
            "INSERT INTO db_helper_test (name) VALUES (?)"
            " ON CONFLICT (name) DO UPDATE SET name = excluded.name",
            ("zolai",),
        )
        conn.commit()
        assert conn.fetchone("SELECT COUNT(*) FROM db_helper_test")[0] == 1
        assert db.row_to_dict(conn.fetchone("SELECT name FROM db_helper_test")) == {
            "name": "zolai"
        }
        conn.execute("DROP TABLE db_helper_test")
        conn.commit()
    finally:
        conn.close()
